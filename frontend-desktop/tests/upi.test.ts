/**
 * UPI QR tests: URI generation, an independent decode of the QR that is actually encoded (jsQR, vendored under
 * tests/vendor, shares no code with src/lib/qr.ts), merchant UPI ID checks, and the rule that nothing is shown as
 * paid/received unless a cashier verified it.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { buildUpiUri, isValidVpa, parseUpiUri, upiSection, upiQrFor, type UpiRequestData } from '../src/lib/receiptModel.ts';
import { encodeQr, qrLayout, type QrCode } from '../src/lib/qr.ts';
import { upiConfigWarnings, upiStatusView } from '../src/lib/upiStatus.ts';

const jsQR = createRequire(import.meta.url)('./vendor/jsqr/jsQR.cjs') as (data: Uint8ClampedArray, w: number, h: number) => { data: string } | null;

/** Rasterise like the printed receipt (white paper, 4-module quiet zone, black modules) and read it back with jsQR. */
const decode = (qr: QrCode, dots = 8): string | null => {
  const quiet = 4;
  const px = (qr.size + quiet * 2) * dots;
  const data = new Uint8ClampedArray(px * px * 4).fill(255);
  for (let y = 0; y < qr.size; y++)
    for (let x = 0; x < qr.size; x++) {
      if (!qr.modules[y][x]) continue;
      for (let dy = 0; dy < dots; dy++)
        for (let dx = 0; dx < dots; dx++) {
          const i = (((y + quiet) * dots + dy) * px + (x + quiet) * dots + dx) * 4;
          data[i] = data[i + 1] = data[i + 2] = 0;
        }
    }
  return jsQR(data, px, px)?.data ?? null;
};

const VPA = 'merchant@oksbi';
const NAME = 'Urban Food Court';

// ------------------------------------------------------------------ URI generation
test('URI has exactly pa, pn, am, cu, tn in that order, with the configured values', () => {
  const uri = buildUpiUri(VPA, NAME, '26.25', 'ORD-20261104-SOSMI');
  assert.equal(uri, 'upi://pay?pa=merchant@oksbi&pn=Urban%20Food%20Court&am=26.25&cu=INR&tn=ORD-20261104-SOSMI');
  const keys = uri.split('?')[1].split('&').map((p) => p.split('=')[0]);
  assert.deepEqual(keys, ['pa', 'pn', 'am', 'cu', 'tn'], 'no missing and no duplicate parameters');
  assert.ok(!/\s/.test(uri), 'no raw spaces');
  assert.ok(!/%25[0-9A-F]{2}/i.test(uri), 'no double encoding');
  const q = parseUpiUri(uri);
  assert.deepEqual(q, { pa: VPA, pn: NAME, am: '26.25', cu: 'INR', tn: 'ORD-20261104-SOSMI' });
});

test('the amount is always two decimals and exact', () => {
  for (const [input, expected] of [['100', '100.00'], [100, '100.00'], ['1587.6', '1587.60'], [1587.6, '1587.60'], ['0.01', '0.01'], ['26.25', '26.25'], ['99999.99', '99999.99']] as const) {
    assert.equal(parseUpiUri(buildUpiUri(VPA, NAME, input, 'R1')).am, expected, String(input));
  }
});

test('special characters in the name or reference are percent-encoded once and cannot add or override parameters', () => {
  const uri = buildUpiUri(VPA, 'Cafe & Grill&am=1&pa=evil@upi #1 = "100%"', '50', 'ORD&cu=USD 1/2');
  const keys = uri.split('?')[1].split('&').map((p) => p.split('=')[0]);
  assert.deepEqual(keys, ['pa', 'pn', 'am', 'cu', 'tn']);
  const q = parseUpiUri(uri);
  assert.equal(q.pa, VPA);
  assert.equal(q.am, '50.00');
  assert.equal(q.cu, 'INR');
  assert.equal(q.pn, 'Cafe & Grill&am=1&pa=evil@upi #1 = "100%"'.slice(0, 50));
  assert.equal(q.tn, 'ORD&cu=USD 1/2');
});

test('missing, malformed and unsafe inputs never produce a QR payload', () => {
  assert.throws(() => buildUpiUri('', NAME, '10', 'R1'), /UPI ID/);
  assert.throws(() => buildUpiUri('noatsign', NAME, '10', 'R1'), /UPI ID/);
  assert.throws(() => buildUpiUri('a&b@okaxis', NAME, '10', 'R1'), /UPI ID/);
  assert.throws(() => buildUpiUri(VPA, NAME, '', 'R1'), /amount/);
  assert.throws(() => buildUpiUri(VPA, NAME, '0', 'R1'), /amount/);
  assert.throws(() => buildUpiUri(VPA, NAME, '0.00', 'R1'), /amount/);
  assert.throws(() => buildUpiUri(VPA, NAME, '-5', 'R1'), /amount/);
  assert.throws(() => buildUpiUri(VPA, NAME, 'abc', 'R1'), /amount/);
  assert.throws(() => buildUpiUri(VPA, NAME, NaN, 'R1'), /amount/);
  assert.throws(() => buildUpiUri(VPA, NAME, Infinity, 'R1'), /amount/);
  assert.throws(() => buildUpiUri(VPA, NAME, '10', '  '), /reference/);
  assert.throws(() => buildUpiUri(VPA, NAME, '10', '\n\t'), /reference/);
});

test('frontend and backend build byte-identical URIs (fixtures generated by the PHP UpiPaymentService::buildUri)', () => {
  const fixture = JSON.parse(readFileSync(new URL('./fixtures/upi-uri-parity.json', import.meta.url), 'utf8')) as { cases: { vpa: string; name: string; amount: string; reference: string; uri: string }[] };
  assert.ok(fixture.cases.length >= 7);
  for (const c of fixture.cases) {
    assert.equal(buildUpiUri(c.vpa.toLowerCase(), c.name, c.amount, c.reference), c.uri, `${c.name} / ${c.reference}`);
  }
});

// ------------------------------------------------------------------ QR round trip (independent decoder)
test('QR round trip: the decoded text is the original URI and every field matches the payment', () => {
  const cases = [
    ['shubhamzombade68@oksbi', 'Urban Food Court', '26.25', 'ORD-20261104-SOSMI'],
    ['merchant@okaxis', 'MangalMurti Food Court', '200.00', 'ORD-20261104-ABCDE'],
    ['shop.name-1@okhdfcbank', 'Cafe & Grill', '1587.60', 'ORD-20261104-QGE41-2'],
    ['a1@ybl', 'A', '0.01', 'ORD-1'],
    ['long.merchant_name123@paytm', 'The Very Long Business Name Of A Food Court Pvt Ltd', '99999.99', 'ORD-20261104-ZZZZZ-12'],
    ['merchant@okaxis', 'Mangal मराठी', '12.00', 'ORD-9'],
  ] as const;
  for (const [vpa, name, amount, ref] of cases) {
    const uri = buildUpiUri(vpa, name, amount, ref);
    const qr = encodeQr(uri);
    const decoded = decode(qr);
    assert.equal(decoded, uri, `${vpa}: decoded payload is identical to the URI that was encoded`);
    const q = parseUpiUri(decoded!);
    assert.equal(q.pa, vpa);
    assert.equal(q.pn, Array.from(name).slice(0, 50).join(''));
    assert.equal(q.am, amount);
    assert.equal(q.cu, 'INR');
    assert.equal(q.tn, ref);
  }
});

test('QR round trip at the real 58 mm and 80 mm print sizes', () => {
  const uri = buildUpiUri('shubhamzombade68@oksbi', 'Urban Food Court', '26.25', 'ORD-20261104-SOSMI');
  for (const paper of [58, 80] as const) {
    const { qr, layout } = upiQrFor(uri, paper);
    assert.equal(decode(qr, Math.round(layout.moduleMm * 8)), uri, `${paper} mm`);
  }
});

test('a changed merchant UPI ID, amount or reference changes the QR; an old QR is never reused for another bill', () => {
  const base = encodeQr(buildUpiUri('old@oksbi', NAME, '26.25', 'ORD-1'));
  const newVpa = encodeQr(buildUpiUri('new@oksbi', NAME, '26.25', 'ORD-1'));
  const newAmount = encodeQr(buildUpiUri('old@oksbi', NAME, '26.26', 'ORD-1'));
  const newRef = encodeQr(buildUpiUri('old@oksbi', NAME, '26.25', 'ORD-2'));
  const key = (q: QrCode) => q.modules.map((r) => r.map((b) => (b ? 1 : 0)).join('')).join('');
  assert.notEqual(key(base), key(newVpa));
  assert.notEqual(key(base), key(newAmount));
  assert.notEqual(key(base), key(newRef));
  assert.equal(parseUpiUri(decode(newVpa)!).pa, 'new@oksbi');
  assert.equal(parseUpiUri(decode(newAmount)!).am, '26.26');
  assert.equal(parseUpiUri(decode(newRef)!).tn, 'ORD-2');
});

test('layout stays scannable (module size, quiet zone) for a typical payload', () => {
  const qr = encodeQr(buildUpiUri('shubhamzombade68@oksbi', NAME, '26.25', 'ORD-20261104-SOSMI'));
  for (const mm of [36, 44]) assert.ok(qrLayout(qr.size, mm).moduleMm >= 0.5);
});

// ------------------------------------------------------------------ merchant UPI ID
test('UPI ID syntax: well-formed IDs pass, empty and malformed ones fail', () => {
  for (const ok of ['a1@ybl', 'shop.name-1@okhdfcbank', 'Shop_Name@PAYTM', 'merchant@oksbi']) assert.ok(isValidVpa(ok), ok);
  for (const bad of ['', 'noatsign', 'a@b', '@bank', 'name@', 'na me@okaxis', 'a&b=c@okaxis', 'x@1bank', 'name@ok axis', '-x@okaxis']) assert.ok(!isValidVpa(bad), bad);
});

const check = (over: object = {}) => ({ syntax_valid: true, handle: 'oksbi', handle_known: true, suggested_handle: null, test_confirmed: false, test_confirmed_at: null, provider_verified: false, ...over });

test('an unrecognised provider handle warns loudly with a suggestion, and is never silently corrected', () => {
  const w = upiConfigWarnings('shubhamzombade68@oksb', check({ handle: 'oksb', handle_known: false, suggested_handle: 'oksbi' }));
  assert.deepEqual(w.map((x) => x.code), ['handle_unknown', 'untested']);
  assert.equal(w[0].level, 'danger');
  assert.match(w[0].title, /@oksb/);
  assert.match(w[0].text, /Did you mean @oksbi\?/);
  assert.match(w[0].text, /Nothing was changed/);
});

test('a well-formed UPI ID is still reported as untested until the owner confirms a test scan; nothing claims it is verified', () => {
  const untested = upiConfigWarnings('merchant@oksbi', check());
  assert.deepEqual(untested.map((x) => x.code), ['untested']);
  assert.match(untested[0].text, /does not prove the account exists/);
  assert.deepEqual(upiConfigWarnings('merchant@oksbi', check({ test_confirmed: true })), []);
  for (const w of [...untested, ...upiConfigWarnings('x@oksb', check({ handle_known: false, handle: 'oksb' }))]) assert.doesNotMatch(`${w.title} ${w.text}`, /verified successfully|is valid and active/i);
});

test('no warning for a missing or syntactically invalid UPI ID (the form validation owns that message)', () => {
  assert.deepEqual(upiConfigWarnings(null, check()), []);
  assert.deepEqual(upiConfigWarnings('bad id', check({ syntax_valid: false })), []);
  assert.deepEqual(upiConfigWarnings('x@oksbi', undefined), []);
});

// ------------------------------------------------------------------ payment status: QR is never payment
const request = (over: Partial<UpiRequestData> = {}): UpiRequestData => ({
  reference: 'ORD-20261104-SOSMI',
  vpa: 'shubhamzombade68@oksbi',
  payee_name: NAME,
  amount: '26.25',
  status: 'pending',
  verification: null,
  ...over,
});
const receipt = (upi: UpiRequestData | null, over: object = {}) => ({ upi_enabled: true, upi, order: { payment_status: upi?.status === 'paid' ? 'paid' : 'unpaid' }, ...over });

test('QR generated -> pending: the receipt never says paid, received, or verified', () => {
  const s = upiSection(receipt(request()))!;
  assert.equal(s.paid, false);
  assert.equal(s.title, 'SCAN & PAY USING UPI');
  assert.match(s.instructionLine, /PENDING until the cashier confirms it/);
  assert.equal(s.verificationLine, null);
  for (const text of [s.title, s.instructionLine, s.vpaLine, s.amountLine, s.referenceLine]) assert.doesNotMatch(text, /paid via|payment received|verified|\bpaid\b/i, text);
});

test('payment initiated but not confirmed: still pending wording, still no paid wording', () => {
  const s = upiSection(receipt(request({ status: 'initiated' })))!;
  assert.equal(s.paid, false);
  assert.equal(s.title, 'SCAN & PAY USING UPI');
  assert.match(s.instructionLine, /payment started, not yet confirmed/);
  assert.equal(s.verificationLine, null);
  assert.doesNotMatch(`${s.title} ${s.instructionLine}`, /paid via|payment received|verified/i);
});

test('only a request the server marked paid shows the paid record, labelled as a MANUAL verification with who and when', () => {
  const s = upiSection(receipt(request({ status: 'paid', verification: { method: 'manual', verified_at: '2026-11-04T09:09:12+00:00', verified_by: 'Asha Cashier' } })))!;
  assert.equal(s.paid, true);
  assert.equal(s.title, 'PAID VIA UPI - MANUALLY VERIFIED');
  assert.equal(s.instructionLine, '', 'no extra note is printed under a paid title');
  assert.equal(s.verificationLine, null, 'who verified and when is stored on the server, not printed');
  assert.doesNotMatch(`${s.title} ${s.instructionLine}`, /payment received/i, 'no claim of automatic receipt');
});

test('a paid request without a recorded verifier prints the same manual label (older records)', () => {
  const s = upiSection(receipt(request({ status: 'paid', verification: null })))!;
  assert.equal(s.verificationLine, null);
  assert.equal(s.instructionLine, '');
  assert.equal(s.title, 'PAID VIA UPI - MANUALLY VERIFIED');
});

test('failed, cancelled, superseded and refunded requests print no QR at all', () => {
  for (const status of ['failed', 'cancelled', 'superseded', 'refunded']) assert.equal(upiSection(receipt(request({ status }))), null, status);
});

test('a pending QR is not printed when UPI is switched off, but a paid record always reprints', () => {
  assert.equal(upiSection(receipt(request(), { upi_enabled: false })), null);
  assert.equal(upiSection(receipt(request({ status: 'initiated' }), { upi_enabled: false })), null);
  assert.ok(upiSection(receipt(request({ status: 'paid' }), { upi_enabled: false })));
});

test('invalid payment data never becomes a QR (zero amount, bad UPI ID, empty reference)', () => {
  assert.equal(upiSection(receipt(request({ amount: '0.00' }))), null);
  assert.equal(upiSection(receipt(request({ vpa: 'not a vpa' }))), null);
  assert.equal(upiSection(receipt(request({ reference: ' ' }))), null);
  assert.equal(upiSection(receipt(null)), null);
});

test('status labels: only "paid" is paid', () => {
  assert.equal(upiStatusView('paid').paid, true);
  assert.equal(upiStatusView('paid').label, 'Paid - manually verified');
  for (const s of ['pending', 'initiated', 'failed', 'cancelled', 'superseded', 'refunded', 'weird', undefined, null]) {
    const v = upiStatusView(s as string);
    assert.equal(v.paid, false, String(s));
    assert.doesNotMatch(v.label, /^paid|received/i, String(s));
  }
  assert.match(upiStatusView('initiated').label, /not yet verified/);
});

// ------------------------------------------------------------------ preview / print / reprint consistency
test('preview, print and historical reprint of the same bill carry the same QR payload and amount', () => {
  const data = receipt(request({ status: 'paid', verification: { method: 'manual', verified_at: '2026-11-04T09:09:12+00:00', verified_by: 'Asha' } }));
  const preview = upiSection(data)!;
  const print = upiSection(JSON.parse(JSON.stringify(data)))!; // what a later reprint would load from the server
  assert.deepEqual(print, preview);
  const q = parseUpiUri(preview.qrText);
  assert.equal(q.pa, data.upi!.vpa);
  assert.equal(q.tn, data.upi!.reference);
  assert.equal(`Amount: ₹${q.am}`, preview.amountLine);
  assert.equal(decode(encodeQr(preview.qrText)), preview.qrText, 'the QR that is drawn decodes to that payload');
});

test('a reprint after the merchant UPI ID changed still shows the ORIGINAL request, not the new settings', () => {
  const original = request({ status: 'paid', vpa: 'old.merchant@oksbi' });
  const s = upiSection({ ...receipt(original), settings_vpa_now: 'new.merchant@okaxis' } as never)!;
  assert.equal(parseUpiUri(s.qrText).pa, 'old.merchant@oksbi');
  assert.equal(s.vpaLine, 'UPI ID: old.merchant@oksbi');
});
